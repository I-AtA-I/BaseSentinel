
import uuid

from sqlalchemy import (
    Index,
    JSON,
    SmallInteger,
    String,
    Text,
    UniqueConstraint,
    Uuid,
)

from basesentinel import db
from basesentinel.models.base import utcnow_naive


class SecurityEvent(db.Model):
    __tablename__ = "security_events"

    id = db.Column(
        Uuid(as_uuid=True, native_uuid=False),
        primary_key=True,
        default=uuid.uuid4,
    )

    agent_id = db.Column(
        Uuid(as_uuid=True, native_uuid=False),
        db.ForeignKey(
            "agents.id",
            ondelete="RESTRICT",
            name="fk_security_events_agent_id_agents",
        ),
        nullable=False,
    )

    # Generated by the agent and reused when retrying an event.
    event_uid = db.Column(
        Uuid(as_uuid=True, native_uuid=False),
        nullable=False,
    )

    schema_version = db.Column(
        SmallInteger,
        nullable=False,
        default=1,
    )

    category = db.Column(
        String(32),
        nullable=False,
    )

    event_type = db.Column(
        String(80),
        nullable=False,
    )

    severity = db.Column(
        SmallInteger,
        nullable=False,
    )

    source = db.Column(
        String(80),
        nullable=False,
    )

    event_code = db.Column(
        String(64),
        nullable=True,
    )

    message = db.Column(
        Text,
        nullable=False,
    )

    event_data = db.Column(
        JSON,
        nullable=True,
    )

    occurred_at = db.Column(
        db.DateTime(),
        nullable=False,
    )

    received_at = db.Column(
        db.DateTime(),
        nullable=False,
        default=utcnow_naive,
    )

    agent = db.relationship("Agent")

    __table_args__ = (
        UniqueConstraint(
            "agent_id",
            "event_uid",
            name="uq_security_events_agent_event_uid",
        ),
        Index(
            "ix_security_events_agent_occurred",
            "agent_id",
            "occurred_at",
        ),
        Index(
            "ix_security_events_occurred",
            "occurred_at",
        ),
        Index(
            "ix_security_events_severity_occurred",
            "severity",
            "occurred_at",
        ),
        Index(
            "ix_security_events_category_occurred",
            "category",
            "occurred_at",
        ),
    )
